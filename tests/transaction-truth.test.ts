import { describe, it, expect } from "vitest";
import { analyzePaymentScreenshot } from "../lib/transaction-truth/screenshot-forensics";
import { inspectQrPayload } from "../lib/transaction-truth/qr-inspector";

describe("Transaction Truth — Payment Forensics & Settlement Integrity", () => {
  describe("Screenshot OCR & Forensic Analysis", () => {
    it("flags fake payment screenshots generated by spoof APKs", () => {
      const spoofText = `
        Payment Successful!
        Paid ₹5,000 to Amazon Vendor
        UPI Ref No: 000000123456
        Paytm Spoof Simulator v2.1
      `;

      const result = analyzePaymentScreenshot({
        ocrText: spoofText,
        claimedBeneficiary: "Amazon",
      });

      expect(result.isSpoofSuspected).toBe(true);
      expect(result.settlementState).toBe("FAILED");
      expect(result.warningSigns.some((w) => w.includes("fake payment prank APK"))).toBe(true);
      expect(result.forensicChecks.find((c) => c.id === "spoof_apk_detected")?.passed).toBe(false);
    });

    it("flags missing or synthetic UTR sequences", () => {
      const receiptNoUtr = `
        Transfer Complete
        Amount: ₹2,500
        Status: Successful
        No Reference Number Provided
      `;

      const result = analyzePaymentScreenshot({ ocrText: receiptNoUtr });

      expect(result.isSpoofSuspected).toBe(true);
      expect(result.extracted.transactionReference).toBeUndefined();
      expect(result.warningSigns.some((w) => w.includes("Missing bank UTR reference"))).toBe(true);
    });

    it("detects beneficiary mismatch when claimed entity differs from destination VPA", () => {
      const receipt = `
        Payment of ₹12,000 Sent
        Beneficiary: rohit.kumar98@okaxis
        UPI Ref: 432198765432
        Status: Completed
      `;

      const result = analyzePaymentScreenshot({
        ocrText: receipt,
        claimedBeneficiary: "Google",
      });

      expect(result.extracted.recipientVpa).toBe("rohit.kumar98@okaxis");
      expect(result.extracted.transactionReference).toBe("432198765432");

      const check = result.forensicChecks.find((c) => c.id === "beneficiary_mismatch");
      expect(check?.passed).toBe(false);
      expect(result.warningSigns.some((w) => w.includes("Beneficiary mismatch"))).toBe(true);
    });

    it("enforces UNABLE_TO_VERIFY when authoritative banking ledger is unconfirmed", () => {
      const normalReceipt = `
        Paid to Scaler Academy
        Amount: ₹50,000
        UPI Ref: 987654321098
        Status: Successful
      `;

      const result = analyzePaymentScreenshot({
        ocrText: normalReceipt,
        claimedBeneficiary: "Scaler",
      });

      // Cannot claim settled without direct bank/gateway webhook confirmation
      expect(result.settlementState).toBe("UNABLE_TO_VERIFY");
      expect(result.honestLimitationNotice).toContain("NOT proof of settled banking transfer");
    });

    it("confirms CONFIRMED_SETTLED when authoritative bank gateway confirms ledger receipt", () => {
      const normalReceipt = `
        Paid to Scaler Academy
        Amount: ₹50,000
        UPI Ref: 987654321098
      `;

      const result = analyzePaymentScreenshot({
        ocrText: normalReceipt,
        authoritativeBankConfirmed: true,
      });

      expect(result.settlementState).toBe("CONFIRMED_SETTLED");
      expect(result.recommendedAction).toContain("Payment is authoritatively confirmed");
    });
  });

  describe("QR Code Deep Link Inspection", () => {
    it("detects deceptive refund collect traps in UPI QR codes", () => {
      const qrPayload = "upi://pay?pa=refund.desk@okhdfcbank&pn=Instant_Refund&am=1500&tn=Electricity_Cashback_Refund";
      const report = inspectQrPayload(qrPayload);

      expect(report.scheme).toBe("upi");
      expect(report.payeeVpa).toBe("refund.desk@okhdfcbank");
      expect(report.isCollectRequest).toBe(true);
      expect(report.warnings.some((w) => w.includes("DEBIT your account"))).toBe(true);
      expect(report.safeAction).toContain("DO NOT ENTER YOUR UPI PIN");
    });

    it("flags shortened URLs inside QR payloads", () => {
      const qrPayload = "https://bit.ly/claim-bank-reward";
      const report = inspectQrPayload(qrPayload);

      expect(report.scheme).toBe("https");
      expect(report.warnings.some((w) => w.includes("shortened link"))).toBe(true);
    });
  });
});
